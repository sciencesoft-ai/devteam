"""Write DevTeam's distribution identity into the prepared tree.

Upstream reads every value a downstream distribution may change from three small
files that patch 0010 introduces (with upstream values):

    src/kiro_crew/_distribution.py       backend, CLI, services
    website/electron/distribution.js     desktop shell
    website/src/distribution.ts          dashboard

This script regenerates them from devteam.conf (values passed as environment
variables by scripts/distribution.sh), then applies the few identity values that
live in packaging metadata: console-script name, Electron package name, protocol
registration and the nightly package names.

Fails loudly on a bad value or on packaging text it cannot find, so an upstream
change surfaces at build time.
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])

# Config-vocabulary backend ids -> runtime ids (upstream spells Kiro CLI "" at runtime).
BACKENDS = {
    "kas": "kas", "kiro": "", "claude": "claude", "codex": "codex", "opencode": "opencode",
    "pi": "pi", "goose": "goose", "deepseek": "deepseek", "copilot": "copilot", "strands": "strands",
}


def conf(name: str) -> str:
    value = os.environ.get(name, "").strip()
    if not value:
        sys.exit(f"distribution: {name} is not set in devteam.conf")
    return value


def fail(msg: str) -> None:
    sys.exit(f"distribution: {msg}")


product = conf("PRODUCT_NAME")
cli = conf("CLI_NAME")
data_home = conf("DATA_HOME")
port_raw = conf("GATEWAY_PORT")
agent = conf("DEFAULT_AGENT")
scheme = conf("URL_SCHEME")
service = conf("SERVICE_NAME")
desktop_pkg = conf("DESKTOP_PACKAGE_NAME")

if not re.fullmatch(r"[a-z][a-z0-9-]{1,30}", cli):
    fail(f"CLI_NAME {cli!r}: use lowercase letters, digits and '-'")
if not data_home.startswith("~/"):
    fail(f"DATA_HOME {data_home!r} must start with ~/")
parts = tuple(p for p in data_home[2:].split("/") if p)
if not parts or any(p in (".", "..") for p in parts):
    fail(f"DATA_HOME {data_home!r} is not a plain path under ~")
if not port_raw.isdigit() or not 1024 <= int(port_raw) <= 65535:
    fail(f"GATEWAY_PORT {port_raw!r} must be 1024-65535")
port = int(port_raw)
if agent not in BACKENDS:
    fail(f"DEFAULT_AGENT {agent!r}: one of {', '.join(BACKENDS)}")
if not re.fullmatch(r"[a-z][a-z0-9+.-]*", scheme):
    fail(f"URL_SCHEME {scheme!r} is not a valid URL scheme")
for name, value in (("SERVICE_NAME", service), ("DESKTOP_PACKAGE_NAME", desktop_pkg)):
    if not re.fullmatch(r"[a-z][a-z0-9-]*", value):
        fail(f"{name} {value!r}: use lowercase letters, digits and '-'")

leaf = parts[-1].lstrip(".") or cli
py_values = {
    "PRODUCT_NAME": product,
    "CLI_NAME": cli,
    "DATA_HOME_PARTS": parts,
    # A name that never exists: DevTeam must never migrate another product's data.
    "LEGACY_HOME_NAME": f".{leaf}-no-legacy-home",
    "RECOVERY_BREADCRUMB_NAME": f".{leaf}.breadcrumb",
    "WORKSPACE_DIR_NAME": f"{cli}-workspace",
    "DEFAULT_PORT": port,
    "DEFAULT_ACP_BACKEND": BACKENDS[agent],
    "URL_SCHEME": scheme,
    "SERVICE_NAME": service,
    "LAUNCHD_LABEL": f"dev.{service}.gateway",
    "DESKTOP_PACKAGE_NAMES": (desktop_pkg, f"{desktop_pkg}-nightly"),
}


def rewrite_py(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    for key, value in py_values.items():
        new, n = re.subn(rf"^{key} = .*$", f"{key} = {value!r}", text, count=1, flags=re.M)
        if n != 1:
            fail(f"{path}: no '{key} = ' line (did patch 0010 change?)")
        text = new
    path.write_text(text, encoding="utf-8", newline="")


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def write_electron(path: Path) -> None:
    if not path.is_file():
        fail(f"{path} missing (did patch 0010 change?)")
    path.write_text(
        '"use strict";\n'
        "// Distribution identity for the Electron shell -- GENERATED by DevTeam's\n"
        "// scripts/distribution.py from devteam.conf. Mirrors src/kiro_crew/_distribution.py.\n"
        "module.exports = Object.freeze({\n"
        f"  PRODUCT_NAME: {js(product)},\n"
        f"  CLI_NAME: {js(cli)},\n"
        f"  DATA_HOME_PARTS: Object.freeze({js(list(parts))}),\n"
        f"  DEFAULT_PORT: {port},\n"
        f"  URL_SCHEME: {js(scheme)},\n"
        "});\n",
        encoding="utf-8",
        newline="",
    )


def write_ts(path: Path) -> None:
    if not path.is_file():
        fail(f"{path} missing (did patch 0010 change?)")
    path.write_text(
        "/**\n"
        " * Distribution identity for the dashboard -- GENERATED by DevTeam's\n"
        " * `scripts/distribution.py` from `devteam.conf`. Mirrors `src/kiro_crew/_distribution.py`.\n"
        " */\n"
        "export const DISTRIBUTION = {\n"
        f"  productName: {js(product)},\n"
        f"  cliName: {js(cli)},\n"
        f"  defaultPort: {port},\n"
        "  /** Config-vocabulary id of the default harness ('kas', 'kiro', 'claude', ...). */\n"
        f"  defaultAcpBackend: {js(agent)},\n"
        "} as const\n",
        encoding="utf-8",
        newline="",
    )


def add_console_script(path: Path, pattern: str, line: str) -> None:
    """Add the CLI_NAME console script next to `kirocrew` (which stays: it is the
    in-install launcher every internal lookup resolves)."""
    text = path.read_text(encoding="utf-8")
    m = re.search(pattern, text, re.M)
    if not m:
        fail(f"{path}: kirocrew console-script line not found")
    if line not in text:
        text = text[: m.end()] + "\n" + line + text[m.end():]
    path.write_text(text, encoding="utf-8", newline="")


def edit_electron_package(path: Path) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("name") != "kirocrew-desktop":
        fail(f"{path}: unexpected package name {data.get('name')!r}")
    data["name"] = desktop_pkg
    data["desktopName"] = f"{desktop_pkg}.desktop"
    build = data["build"]
    build["linux"]["executableName"] = desktop_pkg
    protocols = build.get("protocols") or []
    if len(protocols) != 1 or protocols[0].get("schemes") != ["kirocrew"]:
        fail(f"{path}: unexpected protocols {protocols!r}")
    protocols[0]["name"] = product
    protocols[0]["schemes"] = [scheme]
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="")


def edit_lockfile(path: Path) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["name"] = desktop_pkg
    if "" in data.get("packages", {}):
        data["packages"][""]["name"] = desktop_pkg
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="")


def edit_text(path: Path, old: str, new: str) -> None:
    text = path.read_text(encoding="utf-8")
    if old not in text:
        fail(f"{path}: {old!r} not found")
    path.write_text(text.replace(old, new), encoding="utf-8", newline="")


def widen_security_rules() -> None:
    """The denied-command rules match the product's own program as ``kiro[-.]?crew``
    (``kirocrew token``, ``pkill kirocrew``, ...). The published CLI name must be
    matched by every one of them, or ``devteam token`` mints a dashboard token
    around the rule. Widening only: the upstream spellings stay matched."""
    alt = cli.replace("-", "[-]")
    total = 0
    for rel in ("src/kiro_crew/security/denied_rules.py", "src/kiro_crew/security/denied_rules_catalog.py"):
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        n = text.count("kiro[-.]?crew")
        if n == 0:
            fail(f"{rel}: no kiro[-.]?crew rule left (upstream changed the self-program rules)")
        path.write_text(text.replace("kiro[-.]?crew", f"(?:kiro[-.]?crew|{alt})"), encoding="utf-8", newline="")
        total += n
    print(f"  security: {total} self-program rule patterns also match `{cli}`")


rewrite_py(ROOT / "src/kiro_crew/_distribution.py")
if cli != "kirocrew":
    widen_security_rules()
write_electron(ROOT / "website/electron/distribution.js")
write_ts(ROOT / "website/src/distribution.ts")
if cli != "kirocrew":
    add_console_script(ROOT / "pyproject.toml", r'^kirocrew = "kiro_crew\._bootstrap:main"$',
                       f'{cli} = "kiro_crew._bootstrap:main"')
    add_console_script(ROOT / "setup.cfg", r"^    kirocrew = kiro_crew\._bootstrap:main$",
                       f"    {cli} = kiro_crew._bootstrap:main")
edit_electron_package(ROOT / "website/electron/package.json")
edit_lockfile(ROOT / "website/electron/package-lock.json")
edit_text(ROOT / "packaging/build-desktop.sh", "kirocrew-desktop-nightly", f"{desktop_pkg}-nightly")

print(f"  identity: {product} | cli {cli} | home ~/{'/'.join(parts)} | port {port} | "
      f"agent {agent} | scheme {scheme}:// | service {service} | desktop {desktop_pkg}")
